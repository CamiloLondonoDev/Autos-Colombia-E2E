import { test, expect } from '../fixtures';
import { exitRecord, subscription, type VehicleType } from '../helpers/data';
import { addDays, cop, display, today } from '../helpers/time';
import type { Page } from '@playwright/test';

const historyRows = (page: Page) => page.locator('[data-testid^="payment-row-"]');
const subRows = (page: Page) => page.locator('[data-testid^="subscription-row-"]');

async function openSubscriptions(page: Page) {
  await page.getByTestId('payments-subscriptions-tab').click();
  await expect(page.getByTestId('payments-subscriptions-view')).toBeVisible();
}

async function createSubscription(
  page: Page,
  s: { plate?: string; owner?: string; type?: VehicleType; method?: 'Cash' | 'Transfer' | 'Card' },
) {
  await page.getByTestId('subscriptions-new-btn').click();
  if (s.plate !== undefined) await page.getByTestId('subscription-plate-input').fill(s.plate);
  if (s.owner !== undefined) await page.getByTestId('subscription-owner-input').fill(s.owner);
  if (s.type) await page.getByTestId('subscription-type-select').selectOption(s.type);
  if (s.method) await page.getByTestId('subscription-method-select').selectOption(s.method);
  await page.getByTestId('subscription-save-btn').click();
}

test.describe('Payment history', () => {
  test('@p0 shows the charge generated by an exit with plate, method and total', async ({ app, page }) => {
    app.seed({ exits: [exitRecord({ id: 1700000000123, plate: 'ABC123', total: 9000, method: 'Transfer' })] });
    await app.goto('payments');

    const row = page.getByTestId('payment-row-1700000000123');
    await expect(row).toBeVisible();
    await expect(row).toContainText('ABC123');
    await expect(row).toContainText('Transfer');
    await expect(row).toContainText('By time');
    await expect(row).toContainText(cop(9000));
  });

  test('@p1 stats: total, count and average', async ({ app, page }) => {
    app.seed({
      exits: [
        exitRecord({ total: 9000, method: 'Cash' }),
        exitRecord({ total: 6000, method: 'Card', plate: 'DEF456' }),
        exitRecord({ total: 3000, method: 'Transfer', plate: 'GHI789' }),
      ],
    });
    await app.goto('payments');

    await expect(page.getByTestId('payments-total-value')).toHaveText(cop(18000));
    await expect(page.getByTestId('payments-count-value')).toHaveText('3');
    await expect(page.getByTestId('payments-average-value')).toHaveText(cop(6000));
  });

  test('@p1 filters by date, type and method', async ({ app, page }) => {
    app.seed({
      exits: [
        exitRecord({ plate: 'TODAY1', total: 9000, method: 'Cash' }),
        exitRecord({ plate: 'YEST01', total: 6000, method: 'Card', daysAgo: 1 }),
        exitRecord({ plate: 'SUB001', total: 80000, method: 'Transfer', isMonthly: true }),
      ],
    });
    await app.goto('payments');
    await expect(historyRows(page)).toHaveCount(3);

    // Date: from today
    await page.getByTestId('payments-from-input').fill(today());
    await page.getByTestId('payments-filter-btn').click();
    await expect(historyRows(page)).toHaveCount(2);
    await expect(page.getByText('YEST01')).toHaveCount(0);

    // Type
    await page.getByTestId('payments-type-select').selectOption('monthly');
    await page.getByTestId('payments-filter-btn').click();
    await expect(historyRows(page)).toHaveCount(1);
    await expect(historyRows(page).first()).toContainText('SUB001');

    await page.getByTestId('payments-type-select').selectOption('time');
    await page.getByTestId('payments-filter-btn').click();
    await expect(historyRows(page)).toHaveCount(1);
    await expect(historyRows(page).first()).toContainText('TODAY1');

    // Method
    await page.getByTestId('payments-type-select').selectOption('');
    await page.getByTestId('payments-from-input').fill(addDays(today(), -6));
    await page.getByTestId('payments-method-select').selectOption('Card');
    await page.getByTestId('payments-filter-btn').click();
    await expect(historyRows(page)).toHaveCount(1);
    await expect(historyRows(page).first()).toContainText('YEST01');
  });

  test('@p1 "View receipt" opens the receipt with the right data', async ({ app, page }) => {
    app.seed({ exits: [exitRecord({ id: 1700000000456, plate: 'ABC123', total: 12000, type: 'Van', method: 'Card' })] });
    await app.goto('payments');

    await page.getByTestId('payment-view-btn-1700000000456').click();
    await expect(page.getByTestId('payments-receipt-modal')).toBeVisible();
    await expect(page.getByTestId('payments-receipt-number')).toContainText('#EXIT-000456');
    await expect(page.getByTestId('payments-receipt-plate')).toHaveText('ABC123');
    await expect(page.getByTestId('payments-receipt-type-space')).toContainText('Van');
    await expect(page.getByTestId('payments-receipt-rows')).toContainText('Card');
    await expect(page.getByTestId('payments-receipt-total')).toContainText(cop(12000));

    await page.getByTestId('payments-receipt-close-btn').click();
    await expect(page.getByTestId('payments-receipt-modal')).toBeHidden();
  });

  test('@p1 empty range shows "No payments recorded..."', async ({ app, page }) => {
    await app.goto('payments');
    await expect(page.getByTestId('payments-empty-message')).toContainText('No payments recorded');
    await expect(historyRows(page)).toHaveCount(0);
    await expect(page.getByTestId('payments-total-value')).toHaveText('$0');
  });
});

test.describe('Subscriptions', () => {
  test('@p0 new subscription: row with expiry in 30 days and a payment in the history', async ({ app, page, dialogs }) => {
    await app.goto('payments');
    await openSubscriptions(page);
    await createSubscription(page, { plate: 'abc123', owner: 'Ana Gómez', type: 'Car', method: 'Cash' });

    const expires = display(addDays(today(), 30));
    expect(dialogs.last).toBe(`Subscription registered for ABC123. Expires on ${expires}.`);

    await expect(subRows(page)).toHaveCount(1);
    await expect(subRows(page).first()).toContainText('ABC123');
    await expect(subRows(page).first()).toContainText('Ana Gómez');
    await expect(subRows(page).first()).toContainText(expires);

    await page.getByTestId('payments-history-tab').click();
    await expect(historyRows(page)).toHaveCount(1);
    await expect(historyRows(page).first()).toContainText('ABC123');
    await expect(historyRows(page).first()).toContainText('Subscription');
    await expect(historyRows(page).first()).toContainText(cop(80000));
  });

  const monthly: [VehicleType, number][] = [
    ['Car', 80000],
    ['Motorcycle', 70000],
    ['Pickup', 80000],
    ['Van', 100000],
  ];
  for (const [type, amount] of monthly) {
    test(`@p1 monthly rate for ${type} is ${cop(amount)}`, async ({ app, page }) => {
      await app.goto('payments');
      await openSubscriptions(page);
      await createSubscription(page, { plate: 'RATE01', owner: 'Owner', type });

      await page.getByTestId('payments-history-tab').click();
      await expect(page.getByTestId('payments-total-value')).toHaveText(cop(amount));
    });
  }

  test('@p1 missing plate or owner shows the required-fields alert', async ({ app, page, dialogs }) => {
    await app.goto('payments');
    await openSubscriptions(page);

    await createSubscription(page, { plate: '', owner: 'Owner' });
    expect(dialogs.last).toBe('Please complete the required fields.');

    await page.getByTestId('subscription-plate-input').fill('ABC123');
    await page.getByTestId('subscription-owner-input').fill('');
    await page.getByTestId('subscription-save-btn').click();
    expect(dialogs.messages.filter((m) => m === 'Please complete the required fields.')).toHaveLength(2);
    await expect(subRows(page)).toHaveCount(0);
  });

  test('@p1 duplicate subscription for a valid plate is rejected', async ({ app, page, dialogs }) => {
    app.seed({ subscriptions: [subscription({ plate: 'ABC123', expiresIn: 12 })] });
    await app.goto('payments');
    await openSubscriptions(page);
    await createSubscription(page, { plate: 'abc123', owner: 'Someone' });

    expect(dialogs.last).toContain('already exists');
    await expect(subRows(page)).toHaveCount(1);
  });

  test('@p1 renew adds 30 days to the expiry and records a new payment', async ({ app, page, dialogs }) => {
    const sub = subscription({ plate: 'REN123', expiresIn: 10, id: 'sub-ren' });
    app.seed({ subscriptions: [sub] });
    await app.goto('payments');
    await openSubscriptions(page);

    await page.getByTestId('subscription-renew-btn-sub-ren').click();
    await page.getByTestId('subscription-save-btn').click();

    const expected = addDays(sub.expirationDate, 30);
    expect(dialogs.last).toContain(`renewed until ${display(expected)}`);
    await expect(page.getByTestId('subscription-row-sub-ren')).toContainText(display(expected));

    await page.getByTestId('payments-history-tab').click();
    await expect(historyRows(page)).toHaveCount(1);
    await expect(page.getByTestId('payments-total-value')).toHaveText(cop(80000));
  });

  test('@p1 renewing an expired subscription counts 30 days from today', async ({ app, page }) => {
    app.seed({ subscriptions: [subscription({ plate: 'EXP123', expiresIn: -10, id: 'sub-exp' })] });
    await app.goto('payments');
    await openSubscriptions(page);

    await page.getByTestId('subscription-renew-btn-sub-exp').click();
    await page.getByTestId('subscription-save-btn').click();

    await expect(page.getByTestId('subscription-row-sub-exp')).toContainText(display(addDays(today(), 30)));
  });

  test('@p1 edit changes owner/type without moving dates or creating a payment', async ({ app, page }) => {
    const sub = subscription({ plate: 'EDT123', owner: 'Old Owner', type: 'Car', expiresIn: 20, id: 'sub-edt' });
    app.seed({ subscriptions: [sub] });
    await app.goto('payments');
    await openSubscriptions(page);

    await page.getByTestId('subscription-edit-btn-sub-edt').click();
    await expect(page.getByTestId('subscription-plate-input')).toBeDisabled();
    await page.getByTestId('subscription-owner-input').fill('New Owner');
    await page.getByTestId('subscription-type-select').selectOption('Van');
    await page.getByTestId('subscription-save-btn').click();

    const row = page.getByTestId('subscription-row-sub-edt');
    await expect(row).toContainText('New Owner');
    await expect(row).toContainText('Van');
    await expect(row).toContainText(display(sub.expirationDate));

    await page.getByTestId('payments-history-tab').click();
    await expect(page.getByTestId('payments-empty-message')).toBeVisible();
  });

  test('@p1 delete asks for confirmation: cancel keeps the row, accept removes it', async ({ app, page, dialogs }) => {
    app.seed({ subscriptions: [subscription({ plate: 'DEL123', expiresIn: 20, id: 'sub-del' })] });
    await app.goto('payments');
    await openSubscriptions(page);

    dialogs.dismissNext();
    await page.getByTestId('subscription-delete-btn-sub-del').click();
    expect(dialogs.last).toContain('Delete the subscription for plate DEL123');
    expect(dialogs.types.at(-1)).toBe('confirm');
    await expect(page.getByTestId('subscription-row-sub-del')).toBeVisible();

    await page.getByTestId('subscription-delete-btn-sub-del').click();
    await expect(page.getByTestId('subscription-row-sub-del')).toHaveCount(0);
    await expect(page.getByTestId('subscriptions-empty-message')).toBeVisible();
  });

  test('@p1 statuses and counters: active, expiring soon and expired (+ alert)', async ({ app, page }) => {
    app.seed({
      subscriptions: [
        subscription({ plate: 'ACT001', expiresIn: 20, id: 's-act' }),
        subscription({ plate: 'UPC001', expiresIn: 3, id: 's-upc' }),
        subscription({ plate: 'EXP001', expiresIn: -2, id: 's-exp' }),
      ],
    });
    await app.goto('payments');
    await openSubscriptions(page);

    await expect(page.getByTestId('subscriptions-active-value')).toHaveText('1');
    await expect(page.getByTestId('subscriptions-upcoming-value')).toHaveText('1');
    await expect(page.getByTestId('subscriptions-expired-value')).toHaveText('1');
    await expect(page.getByTestId('subscriptions-expired-alert')).toBeVisible();
    await expect(page.getByTestId('subscriptions-expired-alert')).toContainText('1 expired subscription');

    await expect(page.getByTestId('subscription-row-s-act')).toContainText('Active');
    await expect(page.getByTestId('subscription-row-s-upc')).toContainText('Expires in 3 days');
    await expect(page.getByTestId('subscription-row-s-exp')).toContainText('Expired');
  });

  test('@p1 the expired alert is hidden when nothing is expired', async ({ app, page }) => {
    app.seed({ subscriptions: [subscription({ plate: 'ACT001', expiresIn: 20 })] });
    await app.goto('payments');
    await openSubscriptions(page);
    await expect(page.getByTestId('subscriptions-expired-alert')).toBeHidden();
  });

  test('@p1 search by plate and by owner', async ({ app, page }) => {
    app.seed({
      subscriptions: [
        subscription({ plate: 'AAA111', owner: 'Laura Pérez', expiresIn: 20 }),
        subscription({ plate: 'BBB222', owner: 'Mateo Ruiz', expiresIn: 20 }),
      ],
    });
    await app.goto('payments');
    await openSubscriptions(page);
    await expect(subRows(page)).toHaveCount(2);

    await page.locator('#subSearch').fill('bbb');
    await expect(subRows(page)).toHaveCount(1);
    await expect(subRows(page).first()).toContainText('BBB222');

    await page.locator('#subSearch').fill('laura');
    await expect(subRows(page)).toHaveCount(1);
    await expect(subRows(page).first()).toContainText('AAA111');

    await page.locator('#subSearch').fill('');
    await expect(subRows(page)).toHaveCount(2);
  });
});
